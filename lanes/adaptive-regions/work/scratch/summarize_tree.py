"""Tables for the cone tree runs (runs/cone_tree_n*_L4_s*.json) -> results/cone_tree.md and stdout."""
import glob, json, os
import numpy as np

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rows = []
for f in sorted(glob.glob(os.path.join(R, 'runs', 'cone_tree_n*_L4_s*.json'))):
    try:
        rows.append(json.load(open(f)))
    except Exception:
        pass
rows.sort(key=lambda r: (r['n'], r['seed']))


def at(r, leaves):
    if leaves is None:
        return None
    for c in r['curve']:
        if c['leaves'] >= leaves:
            return c
    return r['curve'][-1]


out = ['# Cone tree (merging similar linear regions), depth 4, widths 4-6', '',
       'Generated by scratch/summarize_tree.py from runs/cone_tree_n*_L4_s*.json. MEASURED (exploratory). Errors are',
       'nMSE of the full-input mean against an RQMC 2^26 truth; MC and RQMC use the same 2^20 advice paths.', '',
       '| n x L | net | cells | distinct maps | exact-cell err | MC err | RQMC err | leaves to MC err | leaves to 2x exact err | units fixed per leaf at MC err (mean / max) | within-leaf map dispersion at MC err | first 5 splits (layer) |',
       '|---|---|---|---|---|---|---|---|---|---|---|---|']
for r in rows:
    c = at(r, r['leaves_to_mc'])
    fs = ' '.join(f"L{s['layer']}" for s in r['first_splits'][:5])
    out.append(f"| {r['n']} x {r['L']} | {r['seed']} | {r['cells']} | {r['final_leaves']} | {r['err_exact']:.1e} | {r['mc_adv']:.1e} | "
               f"{r['rqmc_adv']:.1e} | {r['leaves_to_mc']} | {r['leaves_to_exact']} | "
               f"{'-' if c is None else '%.1f / %d' % (c['units_fixed_mean'], c['units_fixed_max'])} | "
               f"{'-' if c is None else '%.1e' % c['disp_rel']} | {fs} |")
out += ['', 'Split layers among the first 40 splits (count per layer):', '']
for r in rows:
    cnt = np.bincount([s['layer'] for s in r['first_splits']], minlength=r['L'] + 1)[1:]
    out.append(f"- {r['n']} x {r['L']} net {r['seed']}: " + ', '.join(f'L{i + 1}: {c}' for i, c in enumerate(cnt)))
txt = '\n'.join(out) + '\n'
open(os.path.join(R, 'results', 'cone_tree.md'), 'w').write(txt)
print(txt)
