"""Tables for runs/pattern_chain_n*_L*_s*.json -> results/pattern_chain.md and stdout."""
import glob, json, os, re
import numpy as np

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rows = []
for f in glob.glob(os.path.join(R, 'runs', 'pattern_chain_n*_L*_s*.json')):
    try:
        rows.append(json.load(open(f)))
    except Exception:
        pass
rows.sort(key=lambda r: (r['L'] != 4, r['n'], r['L'], r['seed']))
o = ['# Gate-pattern map and chain estimator', '', 'Generated by scratch/summarize_pc.py. MEASURED (exploratory), 2^20 paths per net.', '',
     '## Pattern map', '',
     '| n x L | net | per-layer patterns | per-layer for 99% | cells | product of layer counts | nonzero transitions / dense | H(s_l+1 given s_l) - H(s_l+1 given s_1..l), bits, per step |',
     '|---|---|---|---|---|---|---|---|']
for r in rows:
    tr = r['transitions']
    o.append(f"| {r['n']} x {r['L']} | {r['seed']} | {', '.join(str(d['patterns']) for d in r['layers'])} | "
             f"{', '.join(str(d['for99']) for d in r['layers'])} | {r['cells']} | {r['prod_layer_patterns']:.3g} | "
             f"{sum(t['nonzero'] for t in tr)} / {sum(t['dense'] for t in tr):.3g} | {', '.join('%.2f' % (t['H_markov'] - t['H_full']) for t in tr)} |")
o += ['', '## Chain estimator (error of the chain against the exact-cell sum from the same ingredients, nMSE)', '',
      '| n x L | net | chain states (order 1) | cells | order-1 chain vs cells | order-2 | full-history (past-only) chain vs cells | exact-ingredient order-1 vs cells | MC, same paths | RQMC, same paths |',
      '|---|---|---|---|---|---|---|---|---|---|']
for r in rows:
    od = {x['order']: x for x in r.get('orders', [])}
    ex = r.get('exact', {})
    o.append(f"| {r['n']} x {r['L']} | {r['seed']} | {r['chain_states']} | {r['cells']} | {od[1]['chain_vs_cells']:.1e} | "
             f"{od[2]['chain_vs_cells']:.1e} | {od[r['L']]['chain_vs_cells']:.1e} | "
             f"{('%.1e' % ex['chain_vs_cells']) if ex else '-'} | {r['mc']:.1e} | {r['rqmc']:.1e} |")
o += ['', '## Structure', '',
      '| n x L | net | past bits needed per unit (mean / max) | of them from the previous layer (mean) | transition eff. rank (99%) / patterns | total correlation per layer (bits) | max pairwise MI | units irrelevant to the mean (of nL) |',
      '|---|---|---|---|---|---|---|---|']
for r in rows:
    b = r.get('bits_needed', [])
    bt = (f"{np.mean([x['bits'] for x in b]):.1f} / {max(x['bits'] for x in b)}" if b else '-')
    bp = (f"{np.mean([x['from_prev_layer'] for x in b]):.1f}" if b else '-')
    rk = ', '.join(f"{t['eff_rank99']}/{r['layers'][t['frm'] - 1]['patterns']}" for t in r['transitions'][:3])
    o.append(f"| {r['n']} x {r['L']} | {r['seed']} | {bt} | {bp} | {rk} | "
             f"{', '.join('%.2f' % t['total_corr'] for t in r['independence'][:4])} | {max(t['max_pair_MI'] for t in r['independence']):.2f} | "
             f"{r['irrelevant_units']} of {r['n'] * r['L']} |")
txt = '\n'.join(o) + '\n'
open(os.path.join(R, 'results', 'pattern_chain.md'), 'w').write(txt)
print(txt)
