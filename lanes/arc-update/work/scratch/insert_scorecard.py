"""Insert results/scorecard.md into arc-update.md between the markers <!-- scorecard start --> / <!-- scorecard end -->
(or at the [SCORECARD] placeholder the first time). Descriptive only."""
import os

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rep = os.path.join(HERE, 'arc-update.md')
card = open(os.path.join(HERE, 'results', 'scorecard.md')).read().strip().split('\n')
body = '\n'.join(card[1:]).strip()   # drop the scorecard's own title line
block = ('<!-- scorecard start -->\nScorecard (results/scorecard.md, generated by scratch/scorecard.py from the hashed '
         'scorers' + "'" + ' outputs; prediction wording abbreviated, PREREG.md has the exact text):\n\n' + body +
         '\n<!-- scorecard end -->')
s = open(rep).read()
if '[SCORECARD]' in s:
    s = s.replace('[SCORECARD]', block)
else:
    a = s.index('<!-- scorecard start -->')
    b = s.index('<!-- scorecard end -->') + len('<!-- scorecard end -->')
    s = s[:a] + block + s[b:]
open(rep, 'w').write(s)
print('inserted', len(card) - 1, 'lines')
