"""Report tables (post-scoring, descriptive): results/tables.md.
T1 ladder along L = n/8: per width and variant, median nMSE, cost (passes), G_MC, G_RQMC (score_lad rows).
T2 256 x 32 budget windows per net: each deterministic method's cost, nMSE, gains, and the cost at which RQMC reaches its
   error (the end of its window), plus the oracle radial-Gaussian ceiling Z.
T3 attribution medians by cut. T4 rank profile."""
import json, math, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import score_lad as SL  # noqa: E402
import score_amend2 as A2  # noqa: E402  (prints its JSON; harmless)

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
RUNS = os.path.join(HERE, 'runs')
SEEDS = {32: list(range(300, 308)), 64: list(range(300, 308)), 128: list(range(300, 308)), 256: list(range(200, 205))}
rows = SL.score(SEEDS)
L = []


def med(xs):
    xs = [x for x in xs if x is not None and np.isfinite(x)]
    return float(np.median(xs)) if xs else float('nan')


L.append('# arc-update result tables (generated by scratch/tables.py)\n')
L.append('## T1. ARC kprop variants along L = n/8 (medians over nets)\n')
L.append('| n | L | variant | nets | nMSE | passes | G_MC | G_RQMC |')
L.append('|---|---|---|---|---|---|---|---|')
for n in (32, 64, 128, 256):
    for v in SL.VARIANTS:
        rs = [r for (nn, s, vv), r in rows.items() if nn == n and vv == v]
        if rs:
            L.append(f"| {n} | {SL.CFG[n]} | {v} | {len(rs)} | {med([r['nmse'] for r in rs]):.2e} | "
                     f"{med([r['passes'] for r in rs]):.0f} | {med([r['gain_mc'] for r in rs]):.3g} | "
                     f"{med([r.get('gain_rqmc') for r in rs]):.3g} |")
L.append('\n## T2. 256 x 32 budget windows per net (end of window = cost at which RQMC reaches the method error)\n')
L.append('| net | method | passes | nMSE | G_MC | G_RQMC | RQMC reaches it at (passes) |')
L.append('|---|---|---|---|---|---|---|')


def rqmc_cost(cur, e):
    Ns, es = cur
    if e >= es[0]:
        return Ns[0] * es[0] / e
    if e <= es[-1]:
        return Ns[-1] * es[-1] / e
    return float(np.exp(np.interp(-np.log(e), -np.log(es), np.log(Ns))))


for s in SEEDS[256]:
    cur = SL.rqmc_curve(256, 32, s)
    if cur is None:
        continue
    items = []
    for v in ('k1', 'k2', 'k2a', 'k3', 'k3f', 'k3fa'):
        if (256, s, v) in rows:
            r = rows[(256, s, v)]
            items.append((f'ARC {v}', r['passes'], r['nmse']))
    p = os.path.join(RUNS, f'attr_s{s}.json')
    if os.path.exists(p):
        A = json.load(open(p))
        m = A['models']['exact_gauss']
        items.append(('exact Gaussian recursion', m['cost'] / (2.0 * 256 * 256 * 32), m['total']))
        Z = max(r['b2'] for r in A['models']['oracle_radgauss']['rows'] if r['l'] in (8, 16, 24))
        items.append(('ideal radial closure (oracle ceiling Z, cost assumed 393-1200)', 393, Z))
    for name, c, e in items:
        L.append(f"| {s} | {name} | {c:.0f} | {e:.2e} | {(1.0 / c) / e:.3g} | {SL.rqmc_at(cur, c) / e:.3g} | "
                 f"{rqmc_cost(cur, e):.0f} |")
L.append('\n## T3. Attribution at 256 x 32 (median over nets of b_l^2 and a_l^2, nMSE)\n')
models = ('arc_k2', 'exact_gauss', 'oracle_gauss', 'oracle_radgauss')
L.append('| cut l | ' + ' | '.join(f'{m} b^2' for m in models) + ' | arc_k2 a^2 |')
L.append('|---|' + '---|' * (len(models) + 1))
att = {s: json.load(open(os.path.join(RUNS, f'attr_s{s}.json'))) for s in SEEDS[256]
       if os.path.exists(os.path.join(RUNS, f'attr_s{s}.json'))}
if att:
    cuts = att[next(iter(att))]['cuts']
    for i, l in enumerate(cuts):
        vals = [med([att[s]['models'][m]['rows'][i]['b2'] for s in att]) for m in models]
        a2 = med([att[s]['models']['arc_k2']['rows'][i]['a2'] for s in att])
        L.append(f'| {l} | ' + ' | '.join(f'{v:.2e}' for v in vals) + f' | {a2:.2e} |')
    L.append(f"\nTotals (median): ARC k2 {med([att[s]['models']['arc_k2']['total'] for s in att]):.2e}, "
             f"exact Gaussian {med([att[s]['models']['exact_gauss']['total'] for s in att]):.2e}; nets {sorted(att)}")
L.append('\n## T4. Third-cumulant structure at 256 x 32 (per net)\n')
L.append('| net | layer | PR3 (registered) | PR3 (unbiased numerator) | covariance PR | cap8 | cap32 |')
L.append('|---|---|---|---|---|---|---|')
for s in SEEDS[256]:
    p = os.path.join(RUNS, f'rank_s{s}.json')
    if not os.path.exists(p):
        continue
    R = json.load(open(p))
    for l in sorted(R['layers'], key=int):
        x = R['layers'][l]
        pr_u = x['tr1'] * x['tr2'] / x['trK2'] if x['trK2'] > 0 else float('nan')
        L.append(f"| {s} | {l} | {x['pr']:.1f} | {pr_u:.1f} | {x['cov_pr']:.1f} | {x['capk']['8']:.3f} | "
                 f"{x['capk']['32']:.3f} |")
os.makedirs(os.path.join(HERE, 'results'), exist_ok=True)
open(os.path.join(HERE, 'results', 'tables.md'), 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
